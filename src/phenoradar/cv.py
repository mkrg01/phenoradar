def _inner_cv_splits(
    config: AppConfig, y: np.ndarray, groups: np.ndarray
) -> list[tuple[np.ndarray, np.ndarray, str]]:
    if config.model_selection.inner_cv_strategy is None:
        raise CVError("model_selection.inner_cv_strategy is required when selection is active")

    indices = np.arange(y.shape[0], dtype=int)
    split_iter: Any
    strategy = config.model_selection.inner_cv_strategy
    if strategy == "logo":
        split_iter = LeaveOneGroupOut().split(indices, y, groups)
    elif strategy == "group_kfold":
        n_splits = config.model_selection.inner_cv_n_splits
        if n_splits is None:
            raise CVError(
                "model_selection.inner_cv_n_splits is required for inner_cv_strategy=group_kfold"
            )
        split_iter = GroupKFold(n_splits=n_splits).split(indices, y, groups)
    else:
        n_splits = config.model_selection.inner_cv_n_splits
        if n_splits is None:
            raise CVError(
                "model_selection.inner_cv_n_splits is required for "
                "inner_cv_strategy=stratified_group_kfold"
            )
        split_iter = StratifiedGroupKFold(
            n_splits=n_splits,
            shuffle=True,
            random_state=config.runtime.seed,
        ).split(indices, y, groups)

    rows: list[tuple[np.ndarray, np.ndarray, str]] = []
    try:
        for inner_fold_index, (train_idx, valid_idx) in enumerate(split_iter, start=1):
            train_idx_array = np.asarray(train_idx, dtype=int)
            valid_idx_array = np.asarray(valid_idx, dtype=int)
            if train_idx_array.size == 0 or valid_idx_array.size == 0:
                raise CVError("Inner CV produced an empty train/validation split")
            if np.unique(y[train_idx_array]).size < 2:
                raise CVError(
                    f"Inner CV fold {inner_fold_index} training split contains "
                    "fewer than two labels"
                )
            rows.append((train_idx_array, valid_idx_array, str(inner_fold_index)))
    except ValueError as exc:
        raise CVError(f"Inner CV split error: {exc}") from exc

    if not rows:
        raise CVError("Inner CV produced zero folds")
    return rows


def _build_inner_cv_preprocessed_folds(
    *,
    config: AppConfig,
    x_source_raw: np.ndarray,
    y_source: np.ndarray,
    groups_source: np.ndarray,
    contrast_groups_source: np.ndarray | None,
    feature_names: list[str],
    warnings: list[str] | None = None,
) -> list[InnerCvPreprocessedFold]:
    def _build() -> list[InnerCvPreprocessedFold]:
        preprocessed_folds: list[InnerCvPreprocessedFold] = []
        x_source_expr = _apply_expression_transform_for_config(config, x_source_raw)
        for train_idx, valid_idx, inner_fold_id in _inner_cv_splits(
            config, y_source, groups_source
        ):
            x_train_expr = x_source_expr[train_idx, :]
            x_valid_expr = x_source_expr[valid_idx, :]
            y_train = y_source[train_idx]
            y_valid = y_source[valid_idx]
            groups_train = groups_source[train_idx]
            contrast_groups_train = (
                None if contrast_groups_source is None else contrast_groups_source[train_idx]
            )

            x_train, x_valid, _selected, _counts = _preprocess_transformed_fold_with_counts(
                config,
                x_train_expr,
                x_valid_expr,
                feature_names,
                y_train=y_train,
                groups_train=contrast_groups_train,
                warnings=warnings,
            )
            sample_weight = _fit_sample_weights(config, y_train, groups_train)
            preprocessed_folds.append(
                InnerCvPreprocessedFold(
                    inner_fold_id=inner_fold_id,
                    x_train=x_train,
                    x_valid=x_valid,
                    y_train=y_train,
                    y_valid=y_valid,
                    sample_weight=sample_weight,
                )
            )
        return preprocessed_folds

    return _with_native_thread_limit_for_config(config, _build)


def _score_candidate_inner_cv(
    *,
    config: AppConfig,
    training_scope_id: str,
    source_sample_set_id: int,
    candidate: Candidate,
    preprocessed_folds: list[InnerCvPreprocessedFold],
    estimator_n_jobs: int | None = None,
    timing_recorder: TimingRecorder | None = None,
    warm_start_estimators: dict[str, LogisticRegression] | None = None,
) -> tuple[float, list[dict[str, Any]]]:
    resolved_estimator_n_jobs = (
        _runtime_n_jobs(config) if estimator_n_jobs is None else int(estimator_n_jobs)
    )
    if resolved_estimator_n_jobs < 1:
        raise CVError("estimator_n_jobs must be >= 1")

    def _score() -> tuple[float, list[dict[str, Any]]]:
        fold_scores: list[float] = []
        trial_rows: list[dict[str, Any]] = []
        params_json = json.dumps(candidate.params, ensure_ascii=True, sort_keys=True)

        for fold in preprocessed_folds:
            seed = _deterministic_int_seed(
                f"{config.runtime.seed}|{training_scope_id}|source_{source_sample_set_id}|"
                f"candidate_{candidate.candidate_index}|inner_{fold.inner_fold_id}"
            )
            fresh_estimator = _build_estimator(
                config,
                seed,
                fold.y_train,
                model_params=candidate.params,
                rf_n_jobs=resolved_estimator_n_jobs,
            )
            estimator: LogisticRegression | CalibratedClassifierCV | RandomForestClassifier
            if warm_start_estimators is None:
                estimator = fresh_estimator
            else:
                if not isinstance(fresh_estimator, LogisticRegression):
                    raise CVError("Warm-start candidate path requires logistic regression")
                cached_estimator = warm_start_estimators.get(fold.inner_fold_id)
                if cached_estimator is None:
                    fresh_estimator.set_params(warm_start=True)
                    estimator = fresh_estimator
                    warm_start_estimators[fold.inner_fold_id] = fresh_estimator
                else:
                    cached_estimator.set_params(
                        C=fresh_estimator.C,
                        l1_ratio=fresh_estimator.l1_ratio,
                        max_iter=fresh_estimator.max_iter,
                        random_state=fresh_estimator.random_state,
                        warm_start=True,
                    )
                    estimator = cached_estimator
            fit_diagnostic = _fit_estimator(
                estimator, fold.x_train, fold.y_train, fold.sample_weight
            )
            prob = _predict_positive_probability(estimator, fold.x_valid)
            score = _selection_metric_from_probability(config, fold.y_valid, prob)
            fold_scores.append(score)
            trial_rows.append(
                {
                    "candidate_index": candidate.candidate_index,
                    "inner_fold_id": fold.inner_fold_id,
                    "metric_name": config.model_selection.selection_metric,
                    "metric_value": score,
                    "params_json": params_json,
                    "fit_diagnostic": fit_diagnostic,
                }
            )

        if not fold_scores:
            return np.nan, trial_rows
        fold_score_array = np.asarray(fold_scores, dtype=float)
        if np.all(np.isnan(fold_score_array)):
            return np.nan, trial_rows
        return float(np.nanmean(fold_score_array)), trial_rows

    timing_started = None if timing_recorder is None else timing_recorder.start()
    result = _with_native_thread_limit(resolved_estimator_n_jobs, _score)
    if timing_recorder is not None and timing_started is not None:
        timing_scope, timing_fold_id = _selection_timing_location(training_scope_id)
        timing_recorder.record_since(
            timing_started,
            scope=timing_scope,
            stage="candidate_score",
            fold_id=timing_fold_id,
            sample_set_id=source_sample_set_id,
            candidate_index=candidate.candidate_index,
        )
    return result


def _score_std_error_from_trial_rows(trial_rows: list[dict[str, Any]]) -> float | None:
    values = [
        score
        for row in trial_rows
        if (score := _finite_score(row.get("metric_value"))) is not None
    ]
    if not values:
        return None
    value_array = np.asarray(values, dtype=float)
    return float(np.std(value_array, ddof=0) / np.sqrt(value_array.size))


def _candidate_score_std_errors_from_trial_rows(
    trial_rows: list[dict[str, Any]],
) -> dict[int, float | None]:
    rows_by_candidate: dict[int, list[dict[str, Any]]] = {}
    for row in trial_rows:
        candidate_index_raw = row.get("candidate_index")
        if candidate_index_raw is None:
            continue
        candidate_index = int(candidate_index_raw)
        rows_by_candidate.setdefault(candidate_index, []).append(row)
    return {
        candidate_index: _score_std_error_from_trial_rows(rows)
        for candidate_index, rows in rows_by_candidate.items()
    }


def _tpe_trial_params(
    trial: optuna.Trial,
    *,
    discrete_values: dict[str, list[Any]],
    continuous_values: dict[str, ContinuousSpec],
) -> dict[str, Any]:
    params: dict[str, Any] = {}
    for param_name in sorted(discrete_values.keys()):
        params[param_name] = trial.suggest_categorical(param_name, discrete_values[param_name])
    for param_name in sorted(continuous_values.keys()):
        spec = continuous_values[param_name]
        if hasattr(spec, "start") and hasattr(spec, "end"):
            params[param_name] = trial.suggest_float(param_name, spec.start, spec.end)
        else:
            exponent_name = f"{param_name}__exp"
            exponent = trial.suggest_float(exponent_name, spec.start_exp, spec.end_exp)
            params[param_name] = float(spec.base**exponent)
    return params


def _prepare_source_selection_tpe(
    *,
    config: AppConfig,
    training_scope_id: str,
    source_sample_set_id: int,
    sampled_idx: np.ndarray,
    x_train_raw: np.ndarray,
    y_train: np.ndarray,
    groups_train: np.ndarray,
    feature_names: list[str],
    warnings: list[str],
    progress_callback: Callable[[str, str | None], None] | None = None,
    contrast_groups_train: np.ndarray | None = None,
    timing_recorder: TimingRecorder | None = None,
) -> SourceSelectionResult:
    if not _selection_is_active(config):
        raise CVError(
            "selected_candidate_count/selected_candidate_percent is required "
            "for TPE selection flow"
        )
    if config.model_selection.trial_count is None:
        raise CVError("trial_count is required for TPE strategy")
    runtime_seed = int(config.runtime.seed)
    estimator_n_jobs = _runtime_n_jobs(config)

    x_source_raw = x_train_raw[sampled_idx, :]
    y_source = y_train[sampled_idx]
    groups_source = groups_train[sampled_idx]
    contrast_groups_source = (
        None if contrast_groups_train is None else contrast_groups_train[sampled_idx]
    )
    if np.unique(y_source).size < 2:
        raise CVError(
            "Selection source sampled set became single-class; "
            f"source_sample_set_id={source_sample_set_id}"
        )

    inner_preprocess_started = None if timing_recorder is None else timing_recorder.start()
    preprocessed_folds = _build_inner_cv_preprocessed_folds(
        config=config,
        x_source_raw=x_source_raw,
        y_source=y_source,
        groups_source=groups_source,
        contrast_groups_source=contrast_groups_source,
        feature_names=feature_names,
        warnings=warnings,
    )
    if timing_recorder is not None and inner_preprocess_started is not None:
        timing_scope, timing_fold_id = _selection_timing_location(training_scope_id)
        timing_recorder.record_since(
            inner_preprocess_started,
            scope=timing_scope,
            stage="inner_cv_preprocessing",
            fold_id=timing_fold_id,
            sample_set_id=source_sample_set_id,
        )

    trial_count = int(config.model_selection.trial_count)
    discrete_values, continuous_values = expanded_search_space(config.model_selection.search_space)
    effective_trials = trial_count
    if not continuous_values:
        full_space_size = discrete_candidate_space_size(discrete_values)
        effective_trials = min(trial_count, full_space_size)
        if effective_trials < trial_count:
            warnings.append(
                "model_selection.trial_count exceeded discrete candidate space; "
                f"capped from {trial_count} to {effective_trials} "
                f"for source sample_set_id={source_sample_set_id}"
            )

    local_seed = _deterministic_int_seed(
        f"{runtime_seed}|{training_scope_id}|source_{source_sample_set_id}|tpe_selection"
    )
    metric_name = config.model_selection.selection_metric
    study = optuna.create_study(
        direction=_selection_metric_optuna_direction(metric_name),
        sampler=TPESampler(seed=local_seed),
    )
    nan_sentinel = _selection_metric_nan_sentinel(metric_name)
    trial_rows: list[dict[str, Any]] = []

    def _objective(trial: optuna.Trial) -> float:
        params = _tpe_trial_params(
            trial,
            discrete_values=discrete_values,
            continuous_values=continuous_values,
        )
        candidate = Candidate(candidate_index=trial.number, params=params)
        mean_score, rows = _score_candidate_inner_cv(
            config=config,
            training_scope_id=training_scope_id,
            source_sample_set_id=source_sample_set_id,
            candidate=candidate,
            preprocessed_folds=preprocessed_folds,
            estimator_n_jobs=estimator_n_jobs,
            timing_recorder=timing_recorder,
        )
        trial_rows.extend(rows)
        if progress_callback is not None:
            score_repr = "NA" if np.isnan(mean_score) else f"{float(mean_score):.6f}"
            progress_callback(
                "selection_candidate_done",
                (
                    f"source_sample_set_id={source_sample_set_id}, "
                    f"candidate_index={candidate.candidate_index}, "
                    f"candidate_progress={trial.number + 1}/{effective_trials}, "
                    f"metric_value={score_repr}"
                ),
            )
        trial.set_user_attr("candidate_params", params)
        if np.isnan(mean_score):
            trial.set_user_attr("valid_metric_value", False)
            return nan_sentinel
        trial.set_user_attr("valid_metric_value", True)
        return float(mean_score)

    study.optimize(_objective, n_trials=effective_trials)
    ordered_trials = sorted(study.trials, key=lambda item: item.number)
    scored: list[SelectedCandidate] = []
    score_std_errors = _candidate_score_std_errors_from_trial_rows(trial_rows)
    for trial in ordered_trials:
        params_raw = trial.user_attrs.get("candidate_params")
        if not isinstance(params_raw, dict):
            raise CVError("TPE trial is missing candidate_params user attribute")
        score_value: float | None = None
        if trial.value is not None and bool(trial.user_attrs.get("valid_metric_value", False)):
            score_value = float(trial.value)
        scored.append(
            SelectedCandidate(
                candidate=Candidate(candidate_index=trial.number, params=dict(params_raw)),
                score=score_value,
                score_std_error=score_std_errors.get(trial.number),
                selection_rule=config.model_selection.selection_rule,
            )
        )

    scored_count = len(scored)
    ranked = _rank_selected_candidates(scored, config)
    ranked_unique = _dedupe_ranked_candidates_by_params(ranked)
    available = len(ranked_unique)
    if available < scored_count:
        warnings.append(
            "model_selection deduplicated candidates with identical params; "
            f"reduced from {scored_count} to {available} "
            f"for source sample_set_id={source_sample_set_id}"
        )
    requested_count = _requested_selected_candidate_count(
        config=config,
        available_unique_candidates=available,
    )
    if requested_count is None:
        raise CVError("selected candidate count resolved to null unexpectedly")
    effective_count = min(requested_count, available)
    if effective_count < requested_count:
        warnings.append(
            "model_selection.selected_candidate_count exceeded available candidates; "
            f"capped from {requested_count} to {effective_count} "
            f"for source sample_set_id={source_sample_set_id}"
        )

    return SourceSelectionResult(
        selected_candidates=ranked_unique[:effective_count],
        n_available_candidates=available,
        n_scored_candidates=scored_count,
        selected_candidate_count_requested=requested_count,
        selected_candidate_count_effective=effective_count,
        trial_rows=trial_rows,
    )


def _prepare_source_selection(
    *,
    config: AppConfig,
    training_scope_id: str,
    source_sample_set_id: int,
    sampled_idx: np.ndarray,
    x_train_raw: np.ndarray,
    y_train: np.ndarray,
    groups_train: np.ndarray,
    feature_names: list[str],
    warnings: list[str],
    progress_callback: Callable[[str, str | None], None] | None = None,
    contrast_groups_train: np.ndarray | None = None,
    timing_recorder: TimingRecorder | None = None,
) -> SourceSelectionResult:
    selection_active = _selection_is_active(config)
    if selection_active and config.model_selection.search_strategy == "tpe":
        return _prepare_source_selection_tpe(
            config=config,
            training_scope_id=training_scope_id,
            source_sample_set_id=source_sample_set_id,
            sampled_idx=sampled_idx,
            x_train_raw=x_train_raw,
            y_train=y_train,
            groups_train=groups_train,
            feature_names=feature_names,
            warnings=warnings,
            progress_callback=progress_callback,
            contrast_groups_train=contrast_groups_train,
            timing_recorder=timing_recorder,
        )

    try:
        candidates = generate_candidates(
            config=config,
            training_scope_id=training_scope_id,
            source_sample_set_id=source_sample_set_id,
            warnings=warnings,
        )
    except ModelSelectionError as exc:
        raise CVError(str(exc)) from exc

    if not candidates:
        raise CVError("Model-selection candidate generation produced zero candidates")

    available = len(candidates)

    if not selection_active:
        ranked = [SelectedCandidate(candidate=item, score=None) for item in candidates]
        selected_candidates = _dedupe_ranked_candidates_by_params(ranked)
        if len(selected_candidates) < available:
            warnings.append(
                "model_selection deduplicated candidates with identical params; "
                f"reduced from {available} to {len(selected_candidates)} "
                f"for source sample_set_id={source_sample_set_id}"
            )
        return SourceSelectionResult(
            selected_candidates=selected_candidates,
            n_available_candidates=len(selected_candidates),
            n_scored_candidates=0,
            selected_candidate_count_requested=None,
            selected_candidate_count_effective=len(selected_candidates),
            trial_rows=[],
        )

    x_source_raw = x_train_raw[sampled_idx, :]
    y_source = y_train[sampled_idx]
    groups_source = groups_train[sampled_idx]
    contrast_groups_source = (
        None if contrast_groups_train is None else contrast_groups_train[sampled_idx]
    )
    if np.unique(y_source).size < 2:
        raise CVError(
            "Selection source sampled set became single-class; "
            f"source_sample_set_id={source_sample_set_id}"
        )

    inner_preprocess_started = None if timing_recorder is None else timing_recorder.start()
    preprocessed_folds = _build_inner_cv_preprocessed_folds(
        config=config,
        x_source_raw=x_source_raw,
        y_source=y_source,
        groups_source=groups_source,
        contrast_groups_source=contrast_groups_source,
        feature_names=feature_names,
        warnings=warnings,
    )
    if timing_recorder is not None and inner_preprocess_started is not None:
        timing_scope, timing_fold_id = _selection_timing_location(training_scope_id)
        timing_recorder.record_since(
            inner_preprocess_started,
            scope=timing_scope,
            stage="inner_cv_preprocessing",
            fold_id=timing_fold_id,
            sample_set_id=source_sample_set_id,
        )

    worker_count, estimator_n_jobs = _selection_parallel_plan(config, available)
    scored: list[SelectedCandidate] = []
    trial_rows: list[dict[str, Any]] = []
    if worker_count == 1:
        scored_rows: list[tuple[float, list[dict[str, Any]]]] = []
        warm_start_caches: dict[str, dict[str, LogisticRegression]] = {}
        for candidate_progress, candidate in enumerate(candidates, start=1):
            warm_start_estimators: dict[str, LogisticRegression] | None = None
            if config.model.logistic_warm_start_path:
                path_params = {
                    name: value for name, value in candidate.params.items() if name != "C"
                }
                path_key = json.dumps(path_params, ensure_ascii=True, sort_keys=True)
                warm_start_estimators = warm_start_caches.setdefault(path_key, {})
            mean_score, rows = _score_candidate_inner_cv(
                config=config,
                training_scope_id=training_scope_id,
                source_sample_set_id=source_sample_set_id,
                candidate=candidate,
                preprocessed_folds=preprocessed_folds,
                estimator_n_jobs=estimator_n_jobs,
                timing_recorder=timing_recorder,
                warm_start_estimators=warm_start_estimators,
            )
            scored_rows.append((mean_score, rows))
            if progress_callback is not None:
                score_repr = "NA" if np.isnan(mean_score) else f"{float(mean_score):.6f}"
                progress_callback(
                    "selection_candidate_done",
                    (
                        f"source_sample_set_id={source_sample_set_id}, "
                        f"candidate_index={candidate.candidate_index}, "
                        f"candidate_progress={candidate_progress}/{available}, "
                        f"metric_value={score_repr}"
                    ),
                )
    else:
        if config.model.logistic_warm_start_path:
            warnings.append(
                "model.logistic_warm_start_path was not applied because candidate "
                f"scoring used {worker_count} parallel workers"
            )
        scored_rows_by_index: dict[int, tuple[float, list[dict[str, Any]]]] = {}
        with ThreadPoolExecutor(max_workers=worker_count) as executor:
            futures = {
                executor.submit(
                    _score_candidate_inner_cv,
                    config=config,
                    training_scope_id=training_scope_id,
                    source_sample_set_id=source_sample_set_id,
                    candidate=candidate,
                    preprocessed_folds=preprocessed_folds,
                    estimator_n_jobs=estimator_n_jobs,
                    timing_recorder=timing_recorder,
                ): candidate
                for candidate in candidates
            }
            for candidate_progress, future in enumerate(as_completed(futures), start=1):
                candidate = futures[future]
                mean_score, rows = future.result()
                scored_rows_by_index[candidate.candidate_index] = (mean_score, rows)
                if progress_callback is not None:
                    score_repr = "NA" if np.isnan(mean_score) else f"{float(mean_score):.6f}"
                    progress_callback(
                        "selection_candidate_done",
                        (
                            f"source_sample_set_id={source_sample_set_id}, "
                            f"candidate_index={candidate.candidate_index}, "
                            f"candidate_progress={candidate_progress}/{available}, "
                            f"metric_value={score_repr}"
                        ),
                    )
        scored_rows = [scored_rows_by_index[candidate.candidate_index] for candidate in candidates]

    for candidate, (mean_score, rows) in zip(candidates, scored_rows, strict=True):
        score_value = None if np.isnan(mean_score) else float(mean_score)
        scored.append(
            SelectedCandidate(
                candidate=candidate,
                score=score_value,
                score_std_error=_score_std_error_from_trial_rows(rows),
                selection_rule=config.model_selection.selection_rule,
            )
        )
        trial_rows.extend(rows)

    scored_count = len(scored)
    ranked = _rank_selected_candidates(scored, config)
    ranked_unique = _dedupe_ranked_candidates_by_params(ranked)
    available_unique = len(ranked_unique)
    if available_unique < scored_count:
        warnings.append(
            "model_selection deduplicated candidates with identical params; "
            f"reduced from {scored_count} to {available_unique} "
            f"for source sample_set_id={source_sample_set_id}"
        )

    requested_count = _requested_selected_candidate_count(
        config=config,
        available_unique_candidates=available_unique,
    )
    if requested_count is None:
        raise CVError("selected candidate count resolved to null unexpectedly")
    effective_count = min(requested_count, available_unique)
    if effective_count < requested_count:
        warnings.append(
            "model_selection.selected_candidate_count exceeded available candidates; "
            f"capped from {requested_count} to {effective_count} "
            f"for source sample_set_id={source_sample_set_id}"
        )

    return SourceSelectionResult(
        selected_candidates=ranked_unique[:effective_count],
        n_available_candidates=available_unique,
        n_scored_candidates=scored_count,
        selected_candidate_count_requested=requested_count,
        selected_candidate_count_effective=effective_count,
        trial_rows=trial_rows,
    )


